//! C5 Touch3.5's pinned FT6336 driver: count02, point03..08, gesture D0/D3.
//! One injected contact, no fabricated identity, pressure or gesture engine.
use esp_periph::i2c::I2cDevice;
use std::sync::{Arc, Mutex};

pub struct Ft6336State {
    x: u16, y: u16, down: bool, available: bool, epoch: u64, sequence: u64,
    pending: bool, gesture_enable: Option<bool>, pub reports: u64,
}
impl Ft6336State {
    pub fn new() -> Self { Self { x: 0, y: 0, down: false, available: false, epoch: 0,
        sequence: 0, pending: false, gesture_enable: None, reports: 0 } }
    pub fn set_available(&mut self, yes: bool) {
        if self.available && !yes {
            self.down = false; self.pending = false; self.gesture_enable = None;
            self.epoch = self.epoch.wrapping_add(1); self.sequence = self.sequence.wrapping_add(1);
        }
        self.available = yes;
    }
    pub fn update(&mut self, x: u16, y: u16, down: bool) {
        if !self.available { return; }
        self.x = x.min(319); self.y = y.min(479); self.down = down;
        self.sequence = self.sequence.wrapping_add(1); self.pending = true;
    }
    pub fn irq_high(&self) -> bool { !self.available || !self.pending }
    fn snapshot(&self) -> [u8; 7] {
        [u8::from(self.down), ((self.x >> 8) & 15) as u8, self.x as u8,
            ((self.y >> 8) & 15) as u8, self.y as u8, 0, 0]
    }
}
pub struct Ft6336 {
    state: Arc<Mutex<Ft6336State>>, pointer: Option<u8>, first: bool,
    snapshot: Option<([u8; 7], u64)>, epoch: u64,
}
impl Ft6336 {
    pub fn new(state: Arc<Mutex<Ft6336State>>) -> Self {
        Self { state, pointer: None, first: true, snapshot: None, epoch: 0 }
    }
}
impl I2cDevice for Ft6336 {
    fn start(&mut self, read: bool) -> bool {
        let mut s = self.state.lock().expect("FT6336 state");
        if s.epoch != self.epoch { self.epoch = s.epoch; self.pointer = None; self.snapshot = None; }
        if !s.available { return false; }
        if !read { self.first = true; self.pointer = None; return true; }
        let Some(reg) = self.pointer else { return false; };
        if reg == 2 || ((3..=8).contains(&reg) && self.snapshot.is_none()) {
            self.snapshot = Some((s.snapshot(), s.sequence)); s.reports += 1;
        }
        if reg == 0xd0 && s.gesture_enable.is_none() { return false; }
        (2..=8).contains(&reg) || matches!(reg, 0xd0 | 0xd3)
    }
    fn write(&mut self, byte: u8) -> bool {
        if self.first {
            self.first = false; self.pointer = ((2..=8).contains(&byte) || matches!(byte, 0xd0 | 0xd3)).then_some(byte);
            return self.pointer.is_some();
        }
        let Some(reg) = self.pointer.take() else { return false; };
        let mut s = self.state.lock().expect("FT6336 state");
        match (reg, byte) {
            (0xd0, 0 | 1) => { s.gesture_enable = Some(byte != 0); true }
            (0xd3, 0) => true, // No gesture is generated by this contact-only model.
            _ => false,
        }
    }
    fn read(&mut self) -> u8 {
        let Some(reg) = self.pointer else { return 0xff; };
        let mut s = self.state.lock().expect("FT6336 state");
        let value = match reg {
            2..=8 => self.snapshot.map_or(0xff, |(bytes, _)| bytes[(reg - 2) as usize]),
            0xd0 => s.gesture_enable.map_or(0xff, u8::from),
            0xd3 => 0,
            _ => 0xff,
        };
        let completed = reg == 8 || (reg == 2 && value == 0);
        if completed {
            if self.snapshot.is_some_and(|(_, sequence)| sequence == s.sequence) { s.pending = false; }
            self.snapshot = None;
        }
        self.pointer = if (2..8).contains(&reg) { Some(reg + 1) } else { None };
        value
    }
}

#[cfg(test)] mod tests {
    use super::*;
    fn write(d: &mut dyn I2cDevice, data: &[u8]) -> bool { d.start(false) && data.iter().all(|v| d.write(*v)) }
    #[test] fn ft6336_count_and_coordinates_share_a_snapshot_and_newer_input_is_preserved() {
        let s = Arc::new(Mutex::new(Ft6336State::new())); let mut d = Ft6336::new(s.clone());
        assert!(!d.start(false)); s.lock().unwrap().set_available(true);
        assert!(write(&mut d, &[0xd0, 1])); assert!(write(&mut d, &[0xd0])); assert!(d.start(true)); assert_eq!(d.read(), 1);
        assert!(write(&mut d, &[0xd0, 0])); assert!(write(&mut d, &[0xd3, 0]));
        s.lock().unwrap().update(300, 450, true); assert!(write(&mut d, &[2])); assert!(d.start(true)); assert_eq!(d.read(), 1);
        s.lock().unwrap().update(300, 450, false);
        assert!(write(&mut d, &[3])); assert!(d.start(true)); assert_eq!((0..6).map(|_| d.read()).collect::<Vec<_>>(), [1, 44, 1, 194, 0, 0]);
        assert!(!s.lock().unwrap().irq_high(), "a later release cannot be consumed by old coordinates");
        assert!(write(&mut d, &[2])); assert!(d.start(true)); assert_eq!(d.read(), 0); assert!(s.lock().unwrap().irq_high());
        for reg in [0xa3, 0xa6, 0xa8, 0xff] { assert!(!write(&mut d, &[reg])); }
        assert!(!write(&mut d, &[0xd0, 2])); assert!(!write(&mut d, &[0xd3, 0x20]));
        assert!(write(&mut d, &[2])); s.lock().unwrap().set_available(false); assert!(!d.start(true));
        s.lock().unwrap().set_available(true); assert!(!d.start(true));
        assert!(write(&mut d, &[0xd0])); assert!(!d.start(true), "unknown post-reset gesture default is not invented");
    }
}
