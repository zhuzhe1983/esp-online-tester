#!/usr/bin/env python3
"""Extract exact C5 I2C masks/defaults; this does not implement engines."""
from pathlib import Path
import gzip
import re

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'docs/research/c5-i2c-sources-2026-11-23/components__soc__esp32c5__register__soc__i2c_reg.h.gz'
text = gzip.decompress(SOURCE.read_bytes()).decode()
reg = re.compile(r'/\*\*\s+(\w+_REG) register.*?#define\s+\S+\s+\([^\n]+\+\s+(0x[0-9a-fA-F]+)\)', re.S)
field = re.compile(r'/\*\*\s+\w+\s+:\s*([^;]+);\s*bitpos:\s*\[(\d+)(?::(\d+))?\];\s*default:\s*(0x[0-9a-fA-F]+|\d+);')
regs = list(reg.finditer(text))
lines = ['//! Generated by esp32c5/tools/generate_i2c_registers.py from fixed C5 IDF73550728.',
         'pub(crate) fn config(off:u32)->Option<(u32,u32)>{Some(match off{']
seen = set()
for i, r in enumerate(regs):
    off = int(r[2], 0)
    assert off not in seen
    seen.add(off)
    reset = writable = 0
    body = text[r.end():regs[i+1].start() if i+1 < len(regs) else len(text)]
    for f in field.finditer(body):
        hi, lo = int(f[2]), int(f[3] or f[2])
        mask = ((1 << (hi-lo+1))-1) << lo
        value = int(f[4], 0) << lo
        assert value & ~mask == 0
        reset |= value
        if 'W' in f[1]:
            writable |= mask
    lines.append(f'    0x{off:03x}=>(0x{reset:08x},0x{writable:08x}), // {r[1]}')
lines += ['    _=>return None,', '})}', '']
(ROOT / 'esp32c5/src/i2c_regs.rs').write_text('\n'.join(lines))
