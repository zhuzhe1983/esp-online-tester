#!/usr/bin/env python3
"""C5 metadata only; exposed engines and transfer behavior are explicit Rust."""
from pathlib import Path
import gzip
import re

ROOT = Path(__file__).resolve().parents[2]
SOURCES = ROOT / 'docs/research/c5-transport-sources-2026-11-23'
REG = re.compile(r'/\*\*\s+(\w+_REG(?:\(i\))?) register.*?#define\s+\S+\s+\([^\n]+\+\s+(0x[0-9a-fA-F]+)\)', re.S)
FIELD = re.compile(r'/\*\*\s+\w+\s+:\s*([^;]+);\s*bitpos:\s*\[(\d+)(?::(\d+))?\];\s*default:\s*(0x[0-9a-fA-F]+|\d+);')
lines = ['//! Generated by esp32c5/tools/generate_transport_registers.py.',
         '//! ESP-IDF v5.5.4 735507283d5b2f9fb363a1901172dbd9e847945d C5 headers.',
         'pub(crate) fn config(block: usize, offset: u32) -> Option<(u32, u32)> {',
         '    Some(match (block, offset) {']
for block, name in enumerate(['spi_reg.h', 'ahb_dma_reg.h', 'ledc_reg.h']):
    text = gzip.decompress((SOURCES / ('components__soc__esp32c5__register__soc__' + name + '.gz')).read_bytes()).decode()
    regs = list(REG.finditer(text))
    seen = set()
    for i, reg in enumerate(regs):
        offset = int(reg[2], 0)
        assert offset not in seen, (name, offset)
        seen.add(offset)
        body = text[reg.end():regs[i + 1].start() if i + 1 < len(regs) else len(text)]
        reset = mask = 0
        for field in FIELD.finditer(body):
            high = int(field[2]); low = int(field[3] or field[2])
            bits = ((1 << (high - low + 1)) - 1) << low
            value = int(field[4], 0)
            assert value << low & ~bits == 0, (name, reg[1], field[0])
            reset |= value << low
            if 'W' in field[1]:
                mask |= bits
        lines.append(f'        ({block}, 0x{offset:03x}) => (0x{reset:08x}, 0x{mask:08x}), // {reg[1]}')
lines += ['        _ => return None,', '    })', '}', '']
(ROOT / 'esp32c5/src/transport_regs.rs').write_text('\n'.join(lines))
