import assert from 'node:assert/strict';
import { createFirmwareCache } from '../web/platform/firmware-cache.js';
const hash = 'a'.repeat(64), next = 'b'.repeat(64), cache = createFirmwareCache({ indexedDB: null, maxBytes: 8 });
const data = new Uint8Array([1, 2, 3, 4]);
await cache.putVerified('https://firmware.test/a.bin', hash, data); data[0] = 9;
const hit = await cache.get('https://firmware.test/a.bin', hash);
assert.deepEqual([...hit.data], [1, 2, 3, 4]); hit.data[0] = 8;
assert.equal((await cache.get('https://firmware.test/a.bin', hash)).data[0], 1);
assert.equal(await cache.get('https://firmware.test/a.bin', next), null);
assert.equal(await cache.get('https://firmware.test/b.bin', hash), null);
assert.equal(await cache.get('https://firmware.test/a.bin', hash, 3), null);
await cache.putVerified('https://firmware.test/unpinned', null, data);
assert.equal(await cache.get('https://firmware.test/unpinned', null), null);
await cache.putVerified('https://firmware.test/b.bin', hash, data);
await cache.get('https://firmware.test/a.bin', hash);
await cache.putVerified('https://firmware.test/c.bin', hash, data);
assert.equal(await cache.get('https://firmware.test/b.bin', hash), null);
assert.ok(await cache.get('https://firmware.test/a.bin', hash));
await cache.remove('https://firmware.test/a.bin', hash);
assert.equal(await cache.get('https://firmware.test/a.bin', hash), null);
await cache.clear(); assert.equal(await cache.get('https://firmware.test/c.bin', hash), null);
const blocked = createFirmwareCache({ indexedDB: { open() { throw Error('storage blocked'); } } });
assert.equal(await blocked.putVerified('https://firmware.test/a.bin', hash, data), false);
assert.ok(await blocked.get('https://firmware.test/a.bin', hash));
console.log('ok pinned cache isolation, copy safety, bounded LRU, explicit clear and blocked-storage fallback');
