import assert from 'node:assert/strict';
import {createFirmwareHistory,FIRMWARE_HISTORY_KEY,firmwareHistoryAge,firmwareHistoryName} from '../web/platform/firmware-history.js';
import {firmwareMetadata} from '../web/platform/firmware-metadata.js';
const data=new Map(),storage={getItem:key=>data.get(key),setItem:(key,value)=>data.set(key,value)};
const history=createFirmwareHistory(()=>storage);
const first={url:'https://example.com/releases/fw.bin?a=1&b=2',kind:'merged',productId:'paper',name:'Reader',version:'1.6.5',lastUsedAt:1000};
assert.equal(history.remember(first),true);
history.remember({...first,lastUsedAt:2000});
history.remember({...first,productId:'watch',lastUsedAt:3000});
assert.equal(history.list('paper').length,1);
assert.equal(createFirmwareHistory(()=>storage).list('paper')[0].lastUsedAt,2000);
assert.equal(history.list('paper')[0].url,first.url);
history.remember({...first,sha256:'a'.repeat(64),lastUsedAt:4000});
assert.equal(history.list('paper').length,2,'pinned variants remain separate');
history.clear('paper');assert.equal(history.list().length,1,'clearing one device retains another');
for(const url of ['javascript:alert(1)','https://user:pass@example.com/file','http://example.com/file','invalid']) assert.equal(history.remember({...first,url}),false);
assert.equal(history.remember({...first,sha256:'invalid'}),false);
for(let i=0;i<50;i++)history.remember({...first,url:`https://example.com/${i}.bin`,lastUsedAt:5000+i});
assert.equal(history.list().length,40);assert.ok(history.list()[0].url.endsWith('/49.bin'));
assert.equal(JSON.parse(storage.getItem(FIRMWARE_HISTORY_KEY)).length,40);
const denied=createFirmwareHistory(()=>{throw new Error('denied');});denied.remember(first);assert.equal(denied.persistent,false);assert.equal(denied.list()[0].name,'Reader');
const quota=createFirmwareHistory(()=>({getItem:()=>null,setItem:()=>{throw new Error('quota');}}));quota.remember(first);assert.equal(quota.list().length,1,'failed persistence retains in-page history');
assert.equal(firmwareHistoryAge(1000,61000),'1 分钟前');assert.equal(firmwareHistoryAge(1000,1),'刚刚');
assert.equal(firmwareHistoryName('https://example.com/Reader%20Demo.bin?long=secret'),'Reader Demo.bin');
function app(name,version){const bytes=new Uint8Array(288);const v=new DataView(bytes.buffer);bytes[0]=0xe9;bytes[1]=1;v.setUint32(28,256,true);v.setUint32(32,0xabcd5432,true);bytes.set(new TextEncoder().encode(version),48);bytes.set(new TextEncoder().encode(name),80);return bytes;}
const bytes=app('CrossPoint','1.6.5');
assert.deepEqual(firmwareMetadata([{kind:'app',data:bytes}],null),{name:'CrossPoint',version:'1.6.5',source:'esp-app-description'});
const flash=new Uint8Array(0x20000);flash.set(bytes,0x10000);
assert.equal(firmwareMetadata([{kind:'flash',data:flash}]).version,'1.6.5');
flash.set(app('CrossPoint','2.0.0'),0x11000);
assert.equal(firmwareMetadata([{kind:'flash',data:flash}]).source,'multiple-app-images');
assert.equal(firmwareMetadata([{kind:'app',data:bytes.subarray(0,200)}],{name:'Manifest',version:'1.0'}).name,'Manifest');
assert.equal(firmwareMetadata([{kind:'rom',data:bytes}]).name,'');
console.log('ok firmware history: reload, device isolation, bounded ordering, hash variants, storage denial, URL safety, ESP-IDF metadata and ambiguous OTA images');
